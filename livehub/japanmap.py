W, H = 700, 720


def _xy(lon: float, lat: float) -> tuple[float, float]:
    return round((lon - 128.9) * 40, 1), round((45.7 - lat) * 48, 1)


def _okinawa_xy(lon: float, lat: float) -> tuple[float, float]:
    # 左上の枠(20,30 - 170,180)の中に拡大して置く
    return round(55 + (lon - 127.6) * 110, 1), round(55 + (27.0 - lat) * 110, 1)


def svg() -> str:
    parts = [f'<svg class="jmap" viewBox="0 0 {W} {H}" role="group" aria-label="地方を地図から選ぶ" xmlns="http://www.w3.org/2000/svg">']
    for name, pts in REGIONS.items():
        d = " ".join(f"{x},{y}" for x, y in (_xy(*p) for p in pts))
        parts.append(f'<g class="rg" data-region="{name}" tabindex="0" role="button" aria-label="{name}">'
                     f'<polygon points="{d}"/>')
        if name == "九州・沖縄":
            od = " ".join(f"{x},{y}" for x, y in (_okinawa_xy(*p) for p in OKINAWA))
            parts.append(f'<polygon points="{od}"/>')
        lx, ly = _xy(*LABELS[name])
        parts.append(f'<text x="{lx}" y="{ly}">{name}</text><text class="cnt" x="{lx}" y="{ly + 26}" data-count="{name}"></text></g>')
    parts.append('<rect class="inset" x="20" y="25" width="150" height="150" rx="8"/>')
    parts.append('<text class="insetlabel" x="32" y="48">沖縄</text>')
    parts.append("</svg>")
    return "".join(parts)
